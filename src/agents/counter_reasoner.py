@dataclass
class CounterArgument:
    """A single counter-argument."""

    id: str
    target_argument_id: str  # ID of the argument being countered
    attack_type: str  # "undercut", "rebut", "undermine"
    premise: str
    norm_reference: str
    reasoning: str
    conclusion: str
    strength: float = 0.0  # 0-1 score of how strong the counter-argument is

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "target": self.target_argument_id,
            "attack_type": self.attack_type,
            "premise": self.premise,
            "norm": self.norm_reference,
            "reasoning": self.reasoning,
            "conclusion": self.conclusion,
            "strength": self.strength,
        }


@dataclass
class CounterReasonerOutput:
    """Structured output from the Counter-Reasoner."""

    claim: str
    causality_type: str
    causality_theory: dict
    counter_arguments: list[CounterArgument] = field(default_factory=list)
    attack_graph: dict = field(default_factory=dict)  # Nodes and edges of the attack
    overall_assessment: str = ""  # How strong is the original argument chain
    raw_response: str = ""

    def to_dict(self) -> dict:
        return {
            "claim": self.claim,
            "causality_type": self.causality_type,
            "causality_theory": self.causality_theory,
            "counter_arguments": [ca.to_dict() for ca in self.counter_arguments],
            "attack_graph": self.attack_graph,
            "overall_assessment": self.overall_assessment,
        }


